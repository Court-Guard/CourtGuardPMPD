# ---------------------------------------------------------------------------
# PromptStyle
# ---------------------------------------------------------------------------

class PromptStyle(str, Enum):
    """
    Prompt construction style used by the debate agents.

    HARMONY  : Uses OpenAI Harmony format with system/developer role
               separation. Recommended for gpt-oss models.
               Controlled by COURTGUARD_USE_HARMONY_ROLES=true in .env
    STANDARD : Classic system+user format. Used by all other models
               and as a fallback when harmony roles are unavailable.
    """

    HARMONY  = "harmony"
    STANDARD = "standard"


# ---------------------------------------------------------------------------
# AgentRole
# ---------------------------------------------------------------------------

class AgentRole(str, Enum):
    """
    Role of a debate agent in the evaluation pipeline.

    ATTACKER : Initial screener — sees all categories in lite form.
               Goal: flag potential violations sensitively.
    DEFENDER : Precise evaluator — sees only flagged categories in full.
               Goal: confirm or overturn the attacker's accusation.
               Holds final authority.
    JUDGE    : Optional third agent — called only on tie resolution
               when COURTGUARD_TIE_WINNER=judge.
               Not used in standard PMPD two-agent flow.
    """

    ATTACKER = "attacker"
    DEFENDER = "defender"
    JUDGE    = "judge"


# ---------------------------------------------------------------------------
# OneShotPolarity
# ---------------------------------------------------------------------------

class OneShotPolarity(str, Enum):
    """
    Polarity of a OneShot example stored in a CategoryModule.

    POSITIVE : Example of a policy VIOLATION — what the model should flag.
    NEGATIVE : Example of COMPLIANT content — what the model should allow.

    Both are provided to the Defender to ground its evaluation in
    concrete policy boundaries.

    Note: The existing OneShotSource enum tracks origin (shadow/live).
    OneShotPolarity tracks content type (violation/compliant example).
    These two dimensions are orthogonal — a live shot can be positive
    or negative depending on its verdict.
    """

    POSITIVE = "positive"   # violation example
    NEGATIVE = "negative"   # compliant example


# ---------------------------------------------------------------------------
# TieWinner
# ---------------------------------------------------------------------------

class TieWinner(str, Enum):
    """
    Policy for resolving a tie when all debate rounds are exhausted.

    In the standard PMPD flow this should never trigger because the
    Defender holds final authority. TieWinner is only relevant if
    future extensions add symmetrical round structures.

    DEFENDER : Safe-by-default — if defender never confirmed, result is SAFE.
               Recommended for most safety evaluation tasks.
    ATTACKER : Flag-by-default — if attacker accused and was never
               definitively overturned, result is UNSAFE.
    JUDGE    : Call the optional Judge agent to break the tie.

    Controlled by COURTGUARD_TIE_WINNER in .env.
    """

    DEFENDER = "defender"
    ATTACKER = "attacker"
    JUDGE    = "judge"


# ---------------------------------------------------------------------------
# DebateOutcome
# ---------------------------------------------------------------------------

class DebateOutcome(str, Enum):
    """
    Final outcome of a PMPD debate evaluation.

    SAFE       : Defender confirmed the content is compliant.
    UNSAFE     : Defender confirmed a violation.
    EARLY_SAFE : Attacker found no violation — Defender was never called.
    ERROR      : Debate could not complete due to API or parsing failure.
    """

    SAFE       = "SAFE"
    UNSAFE     = "UNSAFE"
    EARLY_SAFE = "EARLY_SAFE"
    ERROR      = "ERROR"